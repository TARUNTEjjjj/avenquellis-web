import {createHash} from 'node:crypto';
import {readFile,readdir,stat,writeFile} from 'node:fs/promises';
import {dirname,extname,join,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

const projectRoot=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const extensions=new Set(['.html','.js','.mjs','.css','.json','.svg','.png','.jpg','.jpeg','.webp','.ico','.woff','.woff2','.wasm','.webmanifest']);
const excluded=new Set(['sw.js','offline-assets.json','_routes.json']);
export const MAX_ASSET_BYTES=10*1024*1024;
export const MAX_SNAPSHOT_BYTES=32*1024*1024;
const hash=value=>createHash('sha256').update(value).digest('hex');
const sensitiveName=/(?:^|[-_.])(?:secret|secrets|credential|credentials|token|tokens|private-key|api-key|environment)(?:[-_.]|$)/i;

async function collect(directory,prefix='') {
  const assets=[],skipped=[];
  for (const entry of (await readdir(directory,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name,'en'))) {
    const relative=prefix+entry.name;
    if (relative === 'device-runtime' || entry.name.startsWith('.') || sensitiveName.test(entry.name)) {skipped.push(relative);continue;}
    if (entry.isDirectory()) {const child=await collect(join(directory,entry.name),relative+'/');assets.push(...child.assets);skipped.push(...child.skipped);continue;}
    if (!entry.isFile() || excluded.has(relative) || !extensions.has(extname(entry.name).toLowerCase())) continue;
    const file=join(directory,entry.name),size=(await stat(file)).size;
    if (size > MAX_ASSET_BYTES) {skipped.push(relative);continue;}
    const bytes=await readFile(file);
    assets.push({url:relative,bytes:bytes.length,sha256:hash(bytes)});
  }
  return {assets:assets.sort((a,b)=>a.url.localeCompare(b.url,'en')),skipped};
}
function workerSource(manifest) {
  return `/* Generated by scripts/build-offline.mjs. Rebuild after changing any static asset. */
const SNAPSHOT=${JSON.stringify({version:manifest.version,assets:manifest.assets})};
const SCOPE=new URL(self.registration.scope);
const PREFIX='avenquellis-offline:'+SCOPE.pathname+':';
const CACHE=PREFIX+SNAPSHOT.version;
const ASSETS=new Map(SNAPSHOT.assets.map(asset=>[new URL(asset.url,SCOPE).href,asset]));
const INDEX=new URL('index.html',SCOPE).href;
// Keep physical filenames for integrity/cache identity, but use Pages' canonical
// directory URLs on the network and when resolving nested index navigation.
const INDEX_ALIASES=new Map([...ASSETS.keys()].filter(url=>url.endsWith('/index.html')).map(url=>[url.slice(0,-'index.html'.length),url]));
const digest=async bytes=>Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',bytes)),byte=>byte.toString(16).padStart(2,'0')).join('');
async function verifiedFetch(url,asset,timeoutMs=10000) {
  const controller=new AbortController(),timer=setTimeout(()=>controller.abort(),timeoutMs);
  try {
    // Pages redirects every index.html, including nested resource-library pages.
    const networkUrl=url.endsWith('/index.html')?url.slice(0,-'index.html'.length):url;
    const response=await fetch(networkUrl,{cache:'no-store',credentials:'same-origin',redirect:'error',signal:controller.signal});
    if (!response.ok || response.type==='opaque') throw new Error('Asset unavailable');
    const reader=response.body?.getReader();
    if(!reader)throw new Error('Empty asset response');
    const chunks=[];let size=0;
    try{
      while(true){
        const result=await reader.read();if(result.done)break;
        size+=result.value.byteLength;
        if(size>asset.bytes){await reader.cancel();throw new Error('Asset size mismatch');}
        chunks.push(result.value);
      }
    }finally{reader.releaseLock();}
    const bytes=new Uint8Array(size);let offset=0;
    for(const chunk of chunks){bytes.set(chunk,offset);offset+=chunk.byteLength;}
    if(size!==asset.bytes || await digest(bytes)!==asset.sha256)throw new Error('Asset version mismatch');
    const headers=new Headers(response.headers);
    headers.delete('Content-Encoding');headers.delete('Transfer-Encoding');headers.set('Content-Length',String(size));
    return new Response(bytes,{status:response.status,statusText:response.statusText,headers});
  } finally {clearTimeout(timer);}
}
self.addEventListener('install',event=>{
  event.waitUntil((async()=>{
    const cache=await caches.open(CACHE);
    try {
      for (const [url,asset] of ASSETS) await cache.put(url,await verifiedFetch(url,asset));
    } catch (error) {await caches.delete(CACHE);throw error;}
    // Wait for existing tabs to close. Never interrupt a running test with skipWaiting.
  })());
});
self.addEventListener('activate',event=>{
  event.waitUntil((async()=>{
    for (const key of await caches.keys()) if(key.startsWith(PREFIX)&&key!==CACHE) await caches.delete(key);
    // Do not claim existing pages: a page and all its modules keep one snapshot.
  })());
});
self.addEventListener('fetch',event=>{
  const request=event.request;
  if(request.method!=='GET')return;
  const url=new URL(request.url);
  if(url.origin!==SCOPE.origin)return;
  url.hash='';url.search='';
  const cacheUrl=INDEX_ALIASES.get(url.href)||url.href;
  const navigation=request.mode==='navigate'&&(url.href===SCOPE.href||url.href===INDEX);
  const asset=ASSETS.get(cacheUrl);
  if(!navigation&&!asset)return; // No API responses, external PDFs, or arbitrary URLs.
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    if(navigation){
      try {return await verifiedFetch(INDEX,ASSETS.get(INDEX),4000);}
      catch {return await cache.match(INDEX)||new Response('The app is not available offline yet. Reconnect and reload.',{status:503,headers:{'Content-Type':'text/plain; charset=utf-8'}});}
    }
    const saved=await cache.match(cacheUrl);
    if(saved)return saved;
    try {const response=await verifiedFetch(cacheUrl,asset);await cache.put(cacheUrl,response.clone());return response;}
    catch {return new Response('This app asset is unavailable. Reconnect and reopen the app.',{status:503,headers:{'Content-Type':'text/plain; charset=utf-8'}});}
  })());
});
self.addEventListener('message',event=>{
  if(event.data?.type!=='AVENQUELLIS_OFFLINE_STATUS'||!event.ports?.[0])return;
  event.waitUntil((async()=>{
    let ready=false;
    if(await caches.has(CACHE)){
      const cache=await caches.open(CACHE);
      ready=(await Promise.all([...ASSETS.keys()].map(url=>cache.match(url)))).every(Boolean);
    }
    event.ports[0].postMessage({type:'AVENQUELLIS_OFFLINE_STATUS',version:SNAPSHOT.version,ready,assetCount:SNAPSHOT.assets.length});
  })());
});
`;
}
export async function buildOffline({directory=join(projectRoot,'dist')}={}) {
  const {assets,skipped}=await collect(directory);
  for(const required of ['index.html','app.js','style.css','register-offline.js','manifest.webmanifest','icon.svg']) if(!assets.some(a=>a.url===required)) throw new Error(`Required offline asset missing or excluded: ${required}`);
  const totalBytes=assets.reduce((sum,a)=>sum+a.bytes,0);
  if(totalBytes>MAX_SNAPSHOT_BYTES)throw new Error('Offline snapshot exceeds 32MB. Reduce assets before building.');
  // Include the builder implementation in the version so worker behavior updates invalidate old snapshots.
  const builderHash=hash(await readFile(fileURLToPath(import.meta.url)));
  const version=hash(JSON.stringify({builderHash,assets})).slice(0,24);
  const manifest={schemaVersion:1,version,totalBytes,assetCount:assets.length,assets,skipped,limits:{maxAssetBytes:MAX_ASSET_BYTES,maxSnapshotBytes:MAX_SNAPSHOT_BYTES}};
  await writeFile(join(directory,'offline-assets.json'),JSON.stringify(manifest,null,2)+'\n');
  await writeFile(join(directory,'sw.js'),workerSource(manifest));
  return manifest;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  const manifest=await buildOffline();
  console.log(`Offline snapshot ${manifest.version}: ${manifest.assetCount} assets, ${manifest.totalBytes} bytes. ${manifest.skipped.length} files excluded by size/name policy.`);
}
